// Everything the kit writes for a site, rendered from the compiled policy. nginx gets the decision
// table itself (every combination of client kind, path kind and Accept-Language, from
// `decideKinds`), so nginx and the Vercel proxy cannot drift apart.
import { decideKinds, KINDS, PATH_KINDS, AGENT_ORDER } from './classify.mjs';

const GENERATED = 'Generated by anti-ai (anti-ai/bin/anti-ai.mjs) from the site configuration. Do not edit by hand.';

function quote(text) {
    if (/["\\]/.test(text)) {
        throw new Error(`cannot quote for nginx: ${text}`);
    }
    return `"${text}"`;
}

export function robotsTxt(policy, lists) {
    const lines = [
        `# robots.txt for ${policy.name}${policy.origin ? ` (${policy.origin})` : ''}`,
        `# ${GENERATED}`,
        '#',
        "# Automated access, scraping, and any use of this site's content, code or design for AI",
        '# training, AI systems, AI answers or datasets are not permitted. Text and data mining is',
        '# reserved (see /.well-known/tdmrep.json).',
    ];
    if (policy.modes.search === 'info') {
        lines.push(`# Search engines may read the public info page ${policy.origin}${policy.infoPrefix}/ only.`);
    }
    lines.push('');
    if (policy.modes.search === 'info') {
        for (const name of lists.agents.search) {
            lines.push(`User-agent: ${name}`);
        }
        lines.push('Content-Signal: search=yes, ai-input=no, ai-train=no');
        lines.push(`Allow: ${policy.infoPrefix}/`);
        for (const asset of policy.infoAssets) {
            lines.push(`Allow: ${asset}`);
        }
        lines.push('Disallow: /', '');
    }
    const aiNames = [...new Set([...Object.keys(lists.aiRobots), ...lists.agents.ai])].filter((name) => !name.startsWith('__'));
    for (const name of aiNames) {
        lines.push(`User-agent: ${name}`);
    }
    lines.push('Disallow: /', '');
    lines.push('User-agent: *', 'Content-Signal: search=no, ai-input=no, ai-train=no', 'Disallow: /', '');
    return lines.join('\n');
}

export function aiTxt(policy) {
    return [
        `# ai.txt for ${policy.name} (https://site.spawning.ai/spawning-ai-txt)`,
        `# ${GENERATED}`,
        '# No content, code, design or media of this site may be used to train or run AI systems.',
        '',
        'User-Agent: *',
        'Disallow: /',
        'Disallow: *',
        '',
    ].join('\n');
}

/** W3C TDM Reservation Protocol (EU DSM Directive Art. 4(3)): mining is reserved everywhere. */
export function tdmrep() {
    return `${JSON.stringify([{ location: '/*', 'tdm-reservation': 1 }], null, 2)}\n`;
}

/** For the site's HTML <head> (the generated file is a reference; the tags go into the pages). */
export function metaTags(policy) {
    return [
        `<!-- ${GENERATED} -->`,
        '<!-- App and other pages: -->',
        `<meta name="robots" content="${policy.robotsTag.other}" />`,
        '<meta name="tdm-reservation" content="1" />',
        '<!-- The public info page: -->',
        `<meta name="robots" content="${policy.robotsTag.info}" />`,
        '<!-- Trap link for the app shell (invisible, unreachable by keyboard; robots.txt forbids it): -->',
        `<a href="${policy.trapPrefix}/" rel="nofollow" tabindex="-1" aria-hidden="true" hidden>.</a>`,
        '',
    ].join('\n');
}

/** http {} context: classification maps, log format, rate-limit zone, trusted proxies. */
export function nginxHttp(policy, site) {
    const out = [`# ${GENERATED}`, '# Include once in the http context (conf.d/*.conf files are included there).', ''];
    for (const proxy of site.trustedProxies ?? []) {
        if (!/^[0-9a-f.:/]+$/i.test(proxy)) {
            throw new Error(`trustedProxies: ${proxy}`);
        }
        out.push(`set_real_ip_from ${proxy};`);
    }
    if ((site.trustedProxies ?? []).length) {
        out.push('real_ip_header X-Forwarded-For;', 'real_ip_recursive on;', '');
    }
    out.push('# Which client: the first list that matches decides (as in classify.mjs).');
    out.push('map $http_user_agent $anti_ai_ua {', '    default browser;', '    "" bot;');
    for (const kind of AGENT_ORDER) {
        const source = policy.patterns[kind];
        if (source) {
            out.push(`    ${quote(`~*${source}`)} ${kind};`);
        }
    }
    out.push('    "~^[ \t]*$" bot;', '}', '');
    out.push(
        '# Signed AI agents (Web Bot Auth, e.g. ChatGPT agent) are AI whatever their user agent says.',
        'map $http_signature_agent $anti_ai_sig_agent {',
        '    default 1;',
        '    "" 0;',
        '}',
        'map $http_signature_input $anti_ai_sig_input {',
        '    default 0;',
        '    "~*web-bot-auth" 1;',
        '}',
        'map "$anti_ai_sig_agent$anti_ai_sig_input:$anti_ai_ua" $anti_ai_kind {',
        '    default ai;',
        '    "~^00:([a-z]+)$" $1;',
        '}',
        '',
    );
    out.push('# Which path ($uri: decoded and normalised).', 'map $uri $anti_ai_path {', '    default asset;');
    for (const path of policy.publicPaths) {
        out.push(`    ${quote(path)} public;`);
    }
    for (const asset of policy.infoAssets) {
        out.push(`    ${quote(asset)} info-asset;`);
    }
    const prefix = (path) => path.replace(/[^A-Za-z0-9/_-]/g, (c) => `[${c}]`);
    out.push(`    ${quote(`~^${prefix(policy.trapPrefix)}(/|$)`)} trap;`);
    out.push(`    ${quote(`~^${prefix(policy.infoPrefix)}(/|$)`)} info;`);
    out.push('    "~*[.]html$" html;', '    "~/[^/.]*$" html;', '}', '');
    out.push('map $http_accept_language $anti_ai_lang {', '    default 1;', '    "" 0;', '}', '');
    out.push('# The decision table, generated from decideKinds() for every combination.');
    out.push('map "$anti_ai_kind:$anti_ai_path:$anti_ai_lang" $anti_ai_action {', '    default deny;');
    for (const kind of KINDS) {
        for (const path of PATH_KINDS) {
            for (const lang of [0, 1]) {
                out.push(`    ${kind}:${path}:${lang} ${decideKinds(kind, path, lang === 1, policy)};`);
            }
        }
    }
    out.push('}', '');
    out.push(
        'map $anti_ai_path $anti_ai_robots {',
        `    default ${quote(policy.robotsTag.other)};`,
        `    info ${quote(policy.robotsTag.info)};`,
        `    info-asset ${quote(policy.robotsTag.info)};`,
        '}',
        '',
        '# Documents only are rate-limited (an empty key is not limited).',
        'map $anti_ai_path $anti_ai_document_key {',
        '    default "";',
        '    html $binary_remote_addr;',
        '}',
        `limit_req_zone $anti_ai_document_key zone=anti_ai_documents:10m rate=${policy.rateLimit.documentsPerSecond}r/s;`,
        '',
        'map $anti_ai_action $anti_ai_logged {',
        '    default 1;',
        '    allow 0;',
        '}',
        "log_format anti_ai '$remote_addr [$time_local] \"$request\" $status action=$anti_ai_action kind=$anti_ai_kind path=$anti_ai_path ua=\"$http_user_agent\"';",
        '',
    );
    return out.join('\n');
}

/** server {} context: enforcement. Include before the locations. */
export function nginxServer(policy, site) {
    const log = site.nginx?.logFile ?? '/var/log/nginx/anti-ai/anti-ai.log';
    const accessLog = site.nginx?.accessLog ?? '/var/log/nginx/access.log';
    const headers = site.nginx?.headersInclude;
    return [
        `# ${GENERATED}`,
        '# Include in the server {} block, before its locations.',
        '',
        '# A server-level access_log replaces the inherited one, so the normal log is named again.',
        `access_log ${accessLog} combined;`,
        `access_log ${log} anti_ai if=$anti_ai_logged;`,
        '',
        `limit_req zone=anti_ai_documents burst=${policy.rateLimit.burst} nodelay;`,
        'limit_req_status 429;',
        '',
        '# Server-level answers (before any location) carry the policy headers too.',
        'add_header X-Robots-Tag $anti_ai_robots always;',
        'add_header tdm-reservation 1 always;',
        '',
        'error_page 403 @anti_ai_forbidden;',
        'location @anti_ai_forbidden {',
        '    default_type text/plain;',
        headers ? `    include ${headers};` : '    add_header X-Robots-Tag $anti_ai_robots always;\n    add_header tdm-reservation 1 always;',
        '    add_header Cache-Control "no-store" always;',
        `    return 403 ${quote(policy.denyBody.replace(/\n$/, ''))};`,
        '}',
        '',
        'if ($anti_ai_action = trap) {',
        '    return 403;',
        '}',
        'if ($anti_ai_action = deny) {',
        '    return 403;',
        '}',
        '# Internal redirects (index, try_files) run these again: never rewrite the info page itself.',
        'if ($anti_ai_action = info) {',
        `    rewrite ${quote(`^(?!${policy.infoPrefix.replace(/[^A-Za-z0-9/_-]/g, (c) => `[${c}]`)}(/|$))`)} ${policy.infoPrefix}/ last;`,
        '}',
        '',
    ].join('\n');
}

/** For every location with its own add_header (nginx then drops the server-level ones). */
export function nginxHeaders() {
    return [`# ${GENERATED}`, 'add_header X-Robots-Tag $anti_ai_robots always;', 'add_header tdm-reservation 1 always;', ''].join('\n');
}

export function fail2banFilter(action) {
    return [
        `# ${GENERATED}`,
        `# Matches requests the anti-ai nginx rules answered with action=${action}.`,
        '[Definition]',
        `failregex = ^<HOST> \\[[^\\]]+\\] "[^"]*" \\d+ action=${action} `,
        'ignoreregex =',
        'datepattern = %%d/%%b/%%Y:%%H:%%M:%%S %%z',
        '',
    ].join('\n');
}

export function fail2banJail(site) {
    const ban = site.ban ?? {};
    const minutes = Number(ban.minutes ?? 60);
    const chain = ban.chain ?? 'DOCKER-USER';
    const log = ban.logPath ?? '/var/log/anti-ai/anti-ai.log';
    return [
        `# ${GENERATED}`,
        '# Copy to /etc/fail2ban/jail.d/ on the host and the filters to /etc/fail2ban/filter.d/.',
        `# ${log} is the host side of the container's /var/log/nginx/anti-ai/ (bind mount).`,
        "# DOCKER-USER: published container ports bypass the host's INPUT chain; use INPUT without Docker.",
        '',
        '[anti-ai-trap]',
        '# Anyone who follows the hidden trap link (forbidden by robots.txt, invisible to people).',
        'enabled   = true',
        'filter    = anti-ai-trap',
        `logpath   = ${log}`,
        'maxretry  = 1',
        `findtime  = ${minutes}m`,
        `bantime   = ${minutes}m`,
        'port      = http,https',
        'banaction = iptables-multiport',
        `chain     = ${chain}`,
        '',
        '[anti-ai-deny]',
        '# Clients that keep coming back after being refused. Off by default: on mobile networks many',
        '# people share one address (carrier NAT), and one scraper there would lock all of them out.',
        `enabled   = ${ban.denyJail ? 'true' : 'false'}`,
        'filter    = anti-ai-deny',
        `logpath   = ${log}`,
        'maxretry  = 30',
        'findtime  = 10m',
        `bantime   = ${minutes}m`,
        'port      = http,https',
        'banaction = iptables-multiport',
        `chain     = ${chain}`,
        '',
    ].join('\n');
}

